# Trimmed copy of a real pre-commit shim, including the two markers that
# identify it as generated rather than hand-written.
SHIM = """#!/nix/store/xxx-bash-5.3p9/bin/bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03

# start templated
ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit)
# end templated

exec /nix/store/xxx-pre-commit-4.5.1/bin/pre-commit "${ARGS[@]}"
"""

GENUINE_HOOK = """#!/usr/bin/env bash
# A hook someone actually wrote by hand.
make lint
"""


class _FakeRunner:
    """Records invocations instead of shelling out to pre-commit."""

    def __init__(self, returncode: int = 0) -> None:
        self.returncode = returncode
        self.calls: list[tuple[list[str], Path]] = []

    def __call__(self, cmd: Sequence[str], cwd: Path) -> int:
        self.calls.append((list(cmd), cwd))
        return self.returncode


# ---------------------------------------------------------------------------
# Shim detection
# ---------------------------------------------------------------------------


class TestIsHookShim(unittest.TestCase):
    def test_detects_generated_shim(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            p = Path(td) / "pre-commit.legacy"
            p.write_text(SHIM, encoding="utf-8")
            self.assertTrue(is_hook_shim(p))

    def test_rejects_hand_written_hook(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            p = Path(td) / "pre-commit.legacy"
            p.write_text(GENUINE_HOOK, encoding="utf-8")
            self.assertFalse(is_hook_shim(p))

    def test_missing_file_is_not_a_shim(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            self.assertFalse(is_hook_shim(Path(td) / "nope"))

    def test_binary_garbage_does_not_raise(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            p = Path(td) / "pre-commit.legacy"
            p.write_bytes(b"\xff\xfe\x00\x01binary")
            self.assertFalse(is_hook_shim(p))


