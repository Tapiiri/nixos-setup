class TestFindAndClassify(unittest.TestCase):
    def test_finds_only_legacy_files(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            hooks = Path(td)
            (hooks / "pre-commit").write_text(SHIM, encoding="utf-8")
            (hooks / "pre-commit.legacy").write_text(SHIM, encoding="utf-8")
            (hooks / "pre-push.legacy").write_text(SHIM, encoding="utf-8")
            (hooks / "pre-commit.sample").write_text(SHIM, encoding="utf-8")

            found = [p.name for p in find_legacy_hooks(hooks)]
            self.assertEqual(found, ["pre-commit.legacy", "pre-push.legacy"])

    def test_missing_hooks_dir_returns_empty(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            self.assertEqual(find_legacy_hooks(Path(td) / "absent"), [])

    def test_classify_splits_shims_from_genuine_hooks(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            hooks = Path(td)
            shim = hooks / "pre-commit.legacy"
            real = hooks / "pre-push.legacy"
            shim.write_text(SHIM, encoding="utf-8")
            real.write_text(GENUINE_HOOK, encoding="utf-8")

            shims, genuine = classify([shim, real])
            self.assertEqual([p.name for p in shims], ["pre-commit.legacy"])
            self.assertEqual([p.name for p in genuine], ["pre-push.legacy"])


