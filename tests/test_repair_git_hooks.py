class TestRepair(unittest.TestCase):
    def test_force_reinstalls_each_affected_stage(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            shims = [root / "pre-commit.legacy", root / "post-commit.legacy"]
            runner = _FakeRunner()

            rc = repair(
                shims,
                repo_root=root,
                tool="pre-commit",
                config=".pre-commit-config.yaml",
                runner=runner,
            )

            base = ["pre-commit", "install", "-f", "-c", ".pre-commit-config.yaml", "-t"]
            self.assertEqual(rc, 0)
            self.assertEqual(
                [c[0] for c in runner.calls],
                [base + ["pre-commit"], base + ["post-commit"]],
            )

    def test_runs_in_the_repo_root(self) -> None:
        """pre-commit resolves the config and target repo relative to cwd."""
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            runner = _FakeRunner()
            repair(
                [root / "pre-commit.legacy"],
                repo_root=root,
                tool="pre-commit",
                config=".pre-commit-config.yaml",
                runner=runner,
            )
            self.assertEqual(runner.calls[0][1], root)

    def test_reports_failure_when_install_fails(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            root = Path(td)
            rc = repair(
                [root / "pre-commit.legacy"],
                repo_root=root,
                tool="pre-commit",
                config=".pre-commit-config.yaml",
                runner=_FakeRunner(returncode=1),
            )
            self.assertEqual(rc, 1)


