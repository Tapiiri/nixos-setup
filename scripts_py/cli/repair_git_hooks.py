"""Repair git hooks that pre-commit left in "migration mode".

Root cause
----------
devenv installs git hooks by running ``<tool> install -c <config> -t <stage>``
once per configured stage (see the generated ``devenv-git-hooks-install``
script).  It never passes ``-f``/``--overwrite``.

pre-commit recognises its own shims by an MD5 marker embedded in the generated
file — ``CURRENT_HASH`` plus a five-entry ``PRIOR_HASHES`` tuple in
``pre_commit/commands/install_uninstall.py``.  When the installed shim carries
a marker the running binary does not know, ``install`` treats it as a foreign
hook and moves it aside to ``<stage>.legacy`` before writing a fresh shim::

    if os.path.lexists(hook_path) and not is_our_script(hook_path):
        shutil.move(hook_path, legacy_path)

That happens whenever the hook tool changes underneath the repo: devenv's
default ``prek`` versus the pinned ``pkgs.pre-commit``, or a pre-commit release
that rotates the template hash past the end of ``PRIOR_HASHES``.

The backup is then itself a pre-commit shim, so the next commit recurses.  The
new shim sees the ``.legacy`` file, sets ``PRE_COMMIT_RUNNING_LEGACY=1`` and
re-executes it; the nested pre-commit sees that variable already set and aborts
(``pre_commit/commands/hook_impl.py``)::

    bug: pre-commit's script is installed in migration mode

git fails the commit with exit 1 *even though every hook passed* — the failure
is invisible in the hook output, which makes it easy to misread as a check
failure.

Fix
---
``install -f`` deletes the ``.legacy`` file outright, so force-reinstalling the
affected stage is a complete and idempotent repair.  Running this after
``devenv:git-hooks:install`` on every shell entry corrects the state as soon as
it appears, instead of letting it surface at the next commit.

Safety
------
Only ``.legacy`` files that are themselves pre-commit shims are removed.  A
genuine hand-written legacy hook is left alone and reported, because for those
migration mode is a working, intended feature rather than a bug.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Callable, Sequence

from scripts_py.repo.context import repo_root_from_script_path

# Markers found in a pre-commit-generated hook shim.  The first is written by
# pre-commit itself; the second is the invocation every shim ends in, which
# also covers prek's compatible shim.
_SHIM_MARKERS = (
    "File generated by pre-commit",
    "hook-impl",
)

# Takes (cmd, cwd): `pre-commit install` resolves both the config path and the
# target repository relative to its working directory, so cwd is not optional.
Runner = Callable[[Sequence[str], Path], int]


def is_hook_shim(path: Path) -> bool:
    """Return True if ``path`` looks like a generated pre-commit/prek shim.

    Read as bytes and decoded leniently: these files are small shell scripts,
    but a corrupted or binary file must not raise here.
    """
    try:
        contents = path.read_bytes().decode("utf-8", errors="replace")
    except OSError:
        return False
    return any(marker in contents for marker in _SHIM_MARKERS)


def find_legacy_hooks(hooks_dir: Path) -> list[Path]:
    """Return every ``*.legacy`` file in ``hooks_dir``, sorted by name.

    Globbing rather than checking a hardcoded stage list keeps this correct
    whatever ``git-hooks.default_stages`` is set to in devenv.nix.
    """
    if not hooks_dir.is_dir():
        return []
    return sorted(p for p in hooks_dir.glob("*.legacy") if p.is_file())


def classify(legacy_paths: Sequence[Path]) -> tuple[list[Path], list[Path]]:
    """Split legacy hooks into (self-referential shims, genuine user hooks)."""
    shims = [p for p in legacy_paths if is_hook_shim(p)]
    genuine = [p for p in legacy_paths if not is_hook_shim(p)]
    return shims, genuine


def _default_runner(cmd: Sequence[str], cwd: Path) -> int:
    return subprocess.run(list(cmd), cwd=cwd, check=False).returncode


def repair(
    shims: Sequence[Path],
    *,
    repo_root: Path,
    tool: str,
    config: str,
    runner: Runner,
) -> int:
    """Force-reinstall each affected hook stage.  Returns an exit code."""
    failed = False
    for legacy in shims:
        stage = legacy.name.removesuffix(".legacy")
        cmd = [tool, "install", "-f", "-c", config, "-t", stage]
        print(f"[repair-git-hooks] {stage}: force-reinstalling to clear {legacy.name}")
        if runner(cmd, repo_root) != 0:
            print(
                f"[repair-git-hooks] [WARN] `{' '.join(cmd)}` failed; "
                f"remove {legacy} by hand if commits still fail.",
                file=sys.stderr,
            )
            failed = True
    return 1 if failed else 0


def main(
    argv: Sequence[str] | None = None,
    *,
    repo_root: Path | None = None,
    runner: Runner | None = None,
) -> int:
    parser = argparse.ArgumentParser(
        prog="repair-git-hooks",
        description=(
            "Clear pre-commit 'migration mode' left behind when devenv "
            "reinstalls git hooks without -f."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report what would be repaired without changing anything.",
    )
    parser.add_argument(
        "--config",
        default=".pre-commit-config.yaml",
        help="pre-commit config passed to `install -c` (default: %(default)s).",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if repo_root is None:
        try:
            repo_root = repo_root_from_script_path(Path(__file__))
        except FileNotFoundError as exc:
            print(f"[repair-git-hooks] [ERROR] {exc}", file=sys.stderr)
            return 2

    # `--git-common-dir` (not `--git-dir`) so this also works from a worktree,
    # where hooks live in the main checkout's .git directory.
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--git-common-dir"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError as exc:
        print(f"[repair-git-hooks] [ERROR] could not run git: {exc}", file=sys.stderr)
        return 2
    if proc.returncode != 0:
        # Not a git checkout (e.g. a nix build sandbox) — nothing to repair.
        return 0

    git_dir = (repo_root / proc.stdout.strip()).resolve()
    legacy_paths = find_legacy_hooks(git_dir / "hooks")
    if not legacy_paths:
        return 0

    shims, genuine = classify(legacy_paths)

    for path in genuine:
        print(
            f"[repair-git-hooks] leaving {path.name} alone: it is a real hook, "
            f"not a generated shim. Migration mode is intended here.",
        )

    if not shims:
        return 0

    if args.dry_run:
        for path in shims:
            print(f"[repair-git-hooks] would repair: {path}")
        return 0

    tool = shutil.which("pre-commit") or "pre-commit"
    return repair(
        shims,
        repo_root=repo_root,
        tool=tool,
        config=args.config,
        runner=runner or _default_runner,
    )
